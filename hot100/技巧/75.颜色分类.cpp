// ============================================================================
// 【解题思路】荷兰国旗问题（三路 partition）
// ============================================================================
//
// 一、问题本质
// ----------------------------------------------------------------------------
// 这是经典的"荷兰国旗问题"：将数组分成三段，0 在左边，1 在中间，2 在右边。
// 本质上是快速排序中 partition 操作的扩展版本（三路划分而非两路）。
//
// 二、核心思想
// ----------------------------------------------------------------------------
// 用三个指针维护四个区域：
//
//   [  0 区域  ][  1 区域  ][ 待处理 ][  2 区域  ]
//
//   - [0, low-1]     ：已确认的 0（红色）
//   - [low, mid-1]   ：已确认的 1（白色）
//   - [mid, high]    ：待处理区域（未知内容）
//   - [high+1, n-1]  ：已确认的 2（蓝色）
//
// 三、指针移动规则
// ----------------------------------------------------------------------------
// 扫描指针 mid 从左向右遍历，每次处理 nums[mid]：
//
//   1. nums[mid] == 0：
//      - 把 0 换到左边（与 nums[low] 交换）
//      - low++（0 区域扩大）
//      - mid++（换过来的是 1（或 low==mid 时是 0），可以前进）
//
//   2. nums[mid] == 1：
//      - 1 本来就该在中间，不动
//      - mid++（1 区域扩大）
//
//   3. nums[mid] == 2：
//      - 把 2 换到右边（与 nums[high] 交换）
//      - high--（2 区域扩大）
//      - 注意：mid 不动！因为换过来的数还没看过，需要下一轮继续判断
//
// ----------------------------------------------------------------------------
// - 时间复杂度：O(n)，每个元素最多被访问一次
// - 空间复杂度：O(1)，原地操作
// ----------------------------------------------------------------------------
// 想象你在整理背包里的物品：红色药水(0)、普通物品(1)、蓝色药水(2)。
// 你从左往右看，遇到红药水就扔到最左边，遇到蓝药水就扔到最右边，
// 普通物品保持不动，最后背包就按颜色整理好了。
// ============================================================================

// @lc code=start
class Solution {
public:
    void sortColors(vector<int>& nums) {
        int low = 0;
        int high = nums.size() - 1;
        // mid：当前扫描位置
        int mid = 0;

        // 循环条件：mid 越过 high 时，说明待处理区域为空，排序完成
        while (mid <= high) {
            if (nums[mid] == 0) {
                // 当前是 0，需要换到左边
                // 交换后，low 位置变成了 0
                swap(nums[mid], nums[low]);
                low++;   // 0 区域扩大，边界右移
                mid++;   // 换过来的是 1（或 low==mid 时是 0），可以前进
            } else if (nums[mid] == 1) {
                // 当前是 1，恰好在中间区域，跳过即可
                mid++;
            } else {
                // 当前是 2，需要换到右边
                // 交换后，high 位置变成了 2
                swap(nums[mid], nums[high]);
                high--;  // 2 区域扩大，边界左移
                // mid 不动！因为换过来的数还没判断过
            }
        }
    }
};
// @lc code=end
